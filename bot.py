# --- УМНЫЙ ПОИСК ---
@dp.message(Command("start"))
async def start(message: types.Message):
    user_choices[message.from_user.id] = []
    text = (
        "👋 Привет! Я бот-помощник для тренеров по реабилитации.\n\n"
        "Просто напиши, что беспокоит клиента (например, 'болит спина', 'плечо', 'колено'), "
        "и я покажу все возможные варианты.\n\n"
        "⚠️ Это не медицинская рекомендация. Проконсультируйтесь с врачом."
    )
    await message.answer(text)

@dp.message()
async def handle_text(message: types.Message):
    text = message.text.lower().strip()
    user_id = message.from_user.id
    
    # Если ввели цифру
    if text.isdigit() and user_id in user_choices and user_choices[user_id]:
        choice_index = int(text) - 1
        if 0 <= choice_index < len(user_choices[user_id]):
            key = user_choices[user_id][choice_index]
            data = knowledge_base[key]
            answer = f"🔍 *{key.capitalize()}*\n\n"
            answer += "✅ *МОЖНО (на тренажёрах):*\n" + "\n".join([f"• {i}" for i in data["можно"]])
            answer += "\n\n🚫 *НЕЛЬЗЯ / ОСТОРОЖНО:*\n" + "\n".join([f"• {i}" for i in data["нельзя"]])
            answer += f"\n\n📚 *Источники:* {data['ссылки']}"
            answer += "\n\n⚠️ _Это не медицинская рекомендация. Проконсультируйтесь с врачом._"
            await message.answer(answer, parse_mode="Markdown")
            user_choices[user_id] = []
            return
        else:
            await message.answer("Неверный номер. Попробуй ещё раз.")
            return

    # Ищем ВСЕ совпадения по корням слов (первые 4 буквы)
    found_keys = []
    for key in knowledge_base:
        key_words = key.lower().split()
        for word in key_words:
            if len(word) >= 4:
                root = word[:4]
                if root in text:
                    found_keys.append(key)
                    break
    
    if not found_keys:
        await message.answer("Ничего не найдено. Попробуй написать по-другому (например, 'спина', 'колено', 'плечо').")
        return
    
    # Убираем дубликаты
    found_keys = list(set(found_keys))
    
    # Сохраняем варианты
    user_choices[user_id] = found_keys
    
    # Если найдено больше одного варианта, предлагаем список
    if len(found_keys) > 1:
        answer = "🔍 Я нашёл несколько вариантов. Пожалуйста, выбери подходящий:\n\n"
        for i, key in enumerate(found_keys, 1):
            answer += f"{i}. {key.capitalize()}\n"
        answer += "\nНапиши номер варианта (например, 1 или 2), и я дам рекомендации."
        await message.answer(answer)
        return
    
    # Если найден один вариант, сразу выдаем
    key = found_keys[0]
    data = knowledge_base[key]
    answer = f"🔍 *{key.capitalize()}*\n\n"
    answer += "✅ *МОЖНО (на тренажёрах):*\n" + "\n".join([f"• {i}" for i in data["можно"]])
    answer += "\n\n🚫 *НЕЛЬЗЯ / ОСТОРОЖНО:*\n" + "\n".join([f"• {i}" for i in data["нельзя"]])
    answer += f"\n\n📚 *Источники:* {data['ссылки']}"
    answer += "\n\n⚠️ _Это не медицинская рекомендация. Проконсультируйтесь с врачом._"
    await message.answer(answer, parse_mode="Markdown")

